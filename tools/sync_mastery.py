"""Generate the Mastery pages under docs/mastery/ from the mastery repo.

The mastery repo (DungeonBrewOfficial/mastery) is the source of truth. This
script cuts its chapter files into site pages at the headings listed in
SOURCES, cleans up GM Binder markup, writes docs/mastery/, and rewrites the
Mastery block of the nav in mkdocs.yml.

    python tools/sync_mastery.py --source ../mastery

Generated pages start with GENERATED_MARKER (front matter). Never edit them by hand: change
the source and re-run. Pages listed in STUBS are hand-written; the script
creates them once if missing and never touches them again.

The script fails rather than guessing. Every heading at or above a file's
`level` must appear in that file's cut list, so a new or renamed section
stops the sync and names the heading instead of landing on the wrong page.
"""

