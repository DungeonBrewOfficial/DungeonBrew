HEADING = re.compile(r"^(#{1,6})\s+(.*?)\s*#*\s*$")
CENTER = re.compile(r"</?center>", re.IGNORECASE)
RULE = re.compile(r"^\s*(-{3,}|_{3,}|\*{3,})\s*$")
WIDE_DIV = {"<div class='wide'>", '<div class="wide">', "</div>"}


class SyncError(Exception):
    pass


def clean_heading_text(text):
    return " ".join(CENTER.sub("", text).split())


def parse_heading(line):
    m = HEADING.match(line)
    if not m:
        return None
    return len(m.group(1)), clean_heading_text(m.group(2))


def heading_key(depth, text):
    return f"{depth}|{text.casefold()}"


def preprocess(lines):
    """Strip GM Binder markup; tidy heading lines. Returns (text, is_heading) pairs."""
    out = []
    fenced = False
    for line in lines:
        line = line.rstrip("\n").rstrip()
        if line.startswith("```"):
            fenced = not fenced
        if not fenced:
            if line.strip() in WIDE_DIV:
                continue
            h = parse_heading(line)
            if h:
                # GM Binder tolerates a heading glued to a table; MkDocs
                # merges them into one block, so give headings room.
                line = "#" * h[0] + " " + h[1]
                out += [("", False), (line, True), ("", False)]
                continue
        out.append((line, False))
    return out


def split_source(spec, source_dir):
    """Return [(page_key, [lines])] segments for one source file."""
    path = os.path.join(source_dir, spec["file"])
    if not os.path.exists(path):
        raise SyncError(f"{spec['file']}: file not found in {source_dir}")
    with open(path, encoding="utf-8") as f:
        lines = preprocess(f.readlines())

    headings = [(i, *parse_heading(text)) for i, (text, is_h) in enumerate(lines) if is_h]
    if not headings:
        raise SyncError(f"{spec['file']}: no headings found")

    cuts = []
    for heading, target in spec["cuts"]:
        if heading is None:  # whole-file page: cut at the first heading
            _, depth, text = headings[0]
        else:
            h = parse_heading(heading)
            if not h:
                raise SyncError(f"{spec['file']}: bad cut heading {heading!r}")
            depth, text = h
        cuts.append((heading_key(depth, text), target, depth, text))

    cut_at = {}
    for key, target, depth, text in cuts:
        matches = [i for i, d, t in headings if heading_key(d, t) == key]
        shown = "#" * depth + " " + text
        if not matches:
            raise SyncError(f"{spec['file']}: heading {shown!r} not found. "
                            "Was it renamed or removed? Update its cut in SOURCES.")
        if len(matches) > 1:
            raise SyncError(f"{spec['file']}: heading {shown!r} appears "
                            f"{len(matches)} times; cuts must be unique.")
        cut_at[matches[0]] = (target, depth)

    for i, depth, text in headings:
        if depth <= spec["level"] and i not in cut_at:
            raise SyncError(
                f"{spec['file']}:{i + 1}: heading {'#' * depth} {text!r} is not mapped "
                "to a page. Add it to this file's cuts in SOURCES.")

    segments = []
    current = None
    drop_depth = None
    for i, (text, is_h) in enumerate(lines):
        depth = parse_heading(text)[0] if is_h else None
        if drop_depth is not None:
            if depth is not None and depth <= drop_depth:
                drop_depth = None
            else:
                continue
        if i in cut_at:
            target, cut_depth = cut_at[i]
            if target == DROP:
                drop_depth = cut_depth
                continue
            if target == STRIP:
                continue
            current = (target, [])
            segments.append(current)
        if current is None:
            if text.strip():
                raise SyncError(f"{spec['file']}:{i + 1}: content before the first cut heading")
            continue
        current[1].append(text)
    return segments


def trim(lines):
    """Drop blank lines and horizontal rules from both ends."""
    while lines and (not lines[0].strip() or RULE.match(lines[0])):
        lines = lines[1:]
    while lines and (not lines[-1].strip() or RULE.match(lines[-1])):
        lines = lines[:-1]
    return lines


def shift_headings(lines, shift):
    out = []
    for line in lines:
        h = parse_heading(line)
        if h and shift:
            depth = max(2, min(6, h[0] + shift))
            line = "#" * depth + " " + h[1]
        out.append(line)
    return out


def render_page(spec, segments):
    body = []
    for n, lines in enumerate(segments):
        lines = list(lines)
        if n == 0 and spec["lead"]:
            lines = trim(lines[1:])  # page title replaces the lead heading
            depths = [h[0] for h in map(parse_heading, lines) if h]
            shift = 2 - min(depths) if depths else 0
        else:
            shift = 2 - parse_heading(lines[0])[0]
        body.extend(shift_headings(lines, shift))
        body.append("")

    text = [GENERATED_MARKER, "", f"# {spec['title']}", ""]
    if spec["note"]:
        text += ["!!! info \"\"", f"    {spec['note']}", ""]
    text += trim(body)
    out = "\n".join(text) + "\n"
    return re.sub(r"\n{3,}", "\n\n", out)


def nav_lines(node, indent):
    pad = " " * indent
    if isinstance(node, str):
        return [f'{pad}- "{title_of(node)}": mastery/{path_of(node)}']
    title, index, children = node
    lines = [f'{pad}- "{title}":']
    if index:
        lines.append(f"{pad}  - mastery/{path_of(index)}")
    for child in children:
        lines.extend(nav_lines(child, indent + 2))
    return lines


def title_of(key):
    return STUBS[key][1] if key in STUBS else PAGES[key]["title"]


def path_of(key):
    return STUBS[key][0] if key in STUBS else PAGES[key]["path"]


def update_nav(source_rev):
    with open(MKDOCS_YML, encoding="utf-8") as f:
        lines = f.read().split("\n")
    try:
        begin = next(i for i, l in enumerate(lines) if l.strip() == NAV_BEGIN)
        end = next(i for i, l in enumerate(lines) if l.strip() == NAV_END)
    except StopIteration:
        raise SyncError(f"mkdocs.yml: nav markers not found ({NAV_BEGIN!r} ... {NAV_END!r})")
    indent = len(lines[begin]) - len(lines[begin].lstrip())
    block = [lines[begin], f"{' ' * indent}# source: mastery @ {source_rev}"]
    block += nav_lines(NAV, indent)
    lines[begin:end] = block
    with open(MKDOCS_YML, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))


def is_generated(path):
    with open(path, encoding="utf-8") as f:
        return f.read(len(GENERATED_MARKER)) == GENERATED_MARKER


def check_nav_coverage():
    seen = []

    def walk(node):
        if isinstance(node, str):
            seen.append(node)
        else:
            if node[1]:
                seen.append(node[1])
            for c in node[2]:
                walk(c)
    walk(NAV)
    missing = (set(PAGES) | set(STUBS)) - set(seen)
    unknown = set(seen) - set(PAGES) - set(STUBS)
    dupes = {k for k in seen if seen.count(k) > 1}
    if missing or unknown or dupes:
        raise SyncError(f"NAV out of step with PAGES: missing={sorted(missing)} "
                        f"unknown={sorted(unknown)} duplicated={sorted(dupes)}")


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--source", default=os.path.join(os.path.dirname(REPO_ROOT), "mastery"),
                        help="path to a checkout of the mastery repo (default: ../mastery)")
    args = parser.parse_args()
    source_dir = os.path.abspath(args.source)

    check_nav_coverage()
    segments = {key: [] for key in PAGES}
    for spec in SOURCES:
        for key, lines in split_source(spec, source_dir):
            segments[key].append(lines)
    empty = [k for k, segs in segments.items() if not segs]
    if empty:
        raise SyncError(f"pages with no content: {empty}")

    used = {os.path.join(source_dir, s["file"]) for s in SOURCES}
    ignored = sorted(f for f in os.listdir(source_dir)
                     if f.endswith(".md") and os.path.join(source_dir, f) not in used)

    outputs = {os.path.join(OUT_DIR, PAGES[k]["path"]): render_page(PAGES[k], segs)
               for k, segs in segments.items()}

    for path in outputs:
        if os.path.exists(path) and not is_generated(path):
            raise SyncError(f"{os.path.relpath(path, REPO_ROOT)} exists and was not "
                            "generated by this script; refusing to overwrite it.")

    removed = []
    for dirpath, _, files in os.walk(OUT_DIR):
        for name in files:
            path = os.path.join(dirpath, name)
            if name.endswith(".md") and path not in outputs and is_generated(path):
                os.remove(path)
                removed.append(path)

    for path, text in outputs.items():
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8") as f:
            f.write(text)

    created = []
    for rel, title, body in STUBS.values():
        path = os.path.join(OUT_DIR, rel)
        if not os.path.exists(path):
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, "w", encoding="utf-8") as f:
                f.write(f"# {title}\n\n{body}")
            created.append(path)

    try:
        rev = subprocess.run(["git", "-C", source_dir, "rev-parse", "--short", "HEAD"],
                             capture_output=True, text=True, check=True).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        rev = "unknown"
    update_nav(rev)

    print(f"Wrote {len(outputs)} pages from mastery @ {rev}.")
    for path in created:
        print(f"  created stub {os.path.relpath(path, REPO_ROOT)}")
    for path in removed:
        print(f"  removed stale {os.path.relpath(path, REPO_ROOT)}")
    if ignored:
        print("  source files not used by any page: " + ", ".join(ignored))


if __name__ == "__main__":
    try:
        main()
    except SyncError as e:
        sys.exit(f"sync_mastery: {e}")
